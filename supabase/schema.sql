-- 7-1. signup_admin : 이메일·비밀번호·가입 코드로 관리자 계정 생성 + 활성화 + 관리자 등록
--   - 이메일 인증 메일을 보내지 않고 auth.users 에 "이미 확인된" 계정을 직접 만든다.
--   - 가입 코드는 secrets 표의 admin_signup_code 와 비교 (브라우저는 코드를 읽을 수 없음)
--   - 이미 같은 이메일 계정이 있으면 비밀번호는 건드리지 않고 관리자 등록만 보장 (재실행 안전)
--   - 로그인 화면(anon) 과 관리자 대시보드(교사 추가) 양쪽에서 같은 함수를 사용
create or replace function public.signup_admin(
  p_email    text,
  p_password text,
  p_code     text
)
returns json
language plpgsql
security definer
set search_path = public, auth, extensions
as $$
declare
  v_email   text := lower(trim(coalesce(p_email, '')));
  v_code    text;
  v_uid     uuid;
  v_created boolean := false;
begin
  if v_email = '' or position('@' in v_email) = 0 then
    raise exception '올바른 이메일을 입력해 주세요.';
  end if;

  select value into v_code from public.secrets where key = 'admin_signup_code';
  if v_code is null or coalesce(p_code, '') <> v_code then
    raise exception '관리자 가입 코드가 올바르지 않습니다.';
  end if;

  select id into v_uid from auth.users where lower(email) = v_email limit 1;

  if v_uid is null then
    if char_length(coalesce(p_password, '')) < 6 then
      raise exception '비밀번호는 6자 이상이어야 합니다.';
    end if;

    v_uid := gen_random_uuid();

    -- auth.users 에 직접 삽입. (빈 문자열 토큰 칼럼들은 null 이면 로그인 시 오류가 나므로 '' 로 채움)
    insert into auth.users (
      instance_id, id, aud, role, email,
      encrypted_password, email_confirmed_at,
      raw_app_meta_data, raw_user_meta_data,
      is_super_admin, created_at, updated_at,
      confirmation_token, recovery_token,
      email_change, email_change_token_new, email_change_token_current,
      phone_change, phone_change_token, reauthentication_token,
      is_anonymous
    ) values (
      '00000000-0000-0000-0000-000000000000', v_uid, 'authenticated', 'authenticated', v_email,
      extensions.crypt(p_password, extensions.gen_salt('bf')), now(),
      '{"provider":"email","providers":["email"]}'::jsonb, '{}'::jsonb,
      false, now(), now(),
      '', '',
      '', '', '',
      '', '', '',
      false
    );

    -- 이메일 로그인 identity 도 함께 만들어야 비밀번호 로그인이 된다
    insert into auth.identities (
      id, user_id, provider_id, provider, identity_data,
      last_sign_in_at, created_at, updated_at
    ) values (
      gen_random_uuid(), v_uid, v_uid::text, 'email',
      jsonb_build_object('sub', v_uid::text, 'email', v_email,
                         'email_verified', true, 'phone_verified', false),
      now(), now(), now()
    );
    v_created := true;
  end if;

  -- 관리자 목록에 등록 (이미 있으면 그대로)
  insert into public.admins (email) values (v_email) on conflict (email) do nothing;

  return json_build_object('email', v_email, 'created', v_created);
end;
$$;


-- 7-2. remove_admin : 관리자 권한 해제 (본인은 불가). 로그인 계정 자체는 남지만 관리자 기능 사용 불가
create or replace function public.remove_admin(p_email text)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_email text := lower(trim(coalesce(p_email, '')));
begin
  if not public.is_admin() then
    raise exception '관리자만 사용할 수 있습니다.';
  end if;
  if v_email = lower(coalesce(auth.jwt() ->> 'email', '')) then
    raise exception '본인의 관리자 권한은 해제할 수 없습니다.';
  end if;
  delete from public.admins where lower(email) = v_email;
  return found;
end;
$$;


