-- 4-1. settings : 누구나 읽기, 관리자만 수정
drop policy if exists "settings_read_all"    on public.settings;
drop policy if exists "settings_admin_update" on public.settings;
create policy "settings_read_all"     on public.settings for select using (true);
create policy "settings_admin_update" on public.settings for update
  using (public.is_admin()) with check (public.is_admin());

-- 4-2. admins : 관리자만 목록 조회. 추가/삭제는 함수(signup_admin, remove_admin)로만
drop policy if exists "admins_admin_read" on public.admins;
create policy "admins_admin_read" on public.admins for select using (public.is_admin());

-- 4-3. students : 본인 프로필만 조회 / 관리자는 전체 조회·수정·삭제
--      (학생의 insert/update 는 claim_student 함수로만)
drop policy if exists "students_self_read"   on public.students;
drop policy if exists "students_admin_all"   on public.students;
create policy "students_self_read" on public.students for select
  using (auth_uid = auth.uid());
create policy "students_admin_all" on public.students for all
  using (public.is_admin()) with check (public.is_admin());

-- 4-4. artworks : 숨기지 않은 작품은 누구나(로그인 전 포함) 조회, 관리자는 전부 + 쓰기
drop policy if exists "artworks_read_visible" on public.artworks;
drop policy if exists "artworks_admin_all"    on public.artworks;
create policy "artworks_read_visible" on public.artworks for select
  using (hidden = false or public.is_admin());
create policy "artworks_admin_all" on public.artworks for all
  using (public.is_admin()) with check (public.is_admin());

-- 4-5. likes : 학생은 "내가 누른 하트"만 조회 (전체 개수는 artwork_stats 함수로 제공)
--      관리자는 전체 조회·삭제. 학생의 insert/delete 는 toggle_like 함수로만
drop policy if exists "likes_self_read"  on public.likes;
drop policy if exists "likes_admin_all"  on public.likes;
create policy "likes_self_read" on public.likes for select
  using (student_id = public.my_student_id());
create policy "likes_admin_all" on public.likes for all
  using (public.is_admin()) with check (public.is_admin());

-- 4-6. comments : 숨기지 않은 댓글은 누구나 조회(masked_name 만 노출됨)
--      관리자는 전부 조회 + 숨김/삭제. 학생의 insert/delete 는 함수로만
drop policy if exists "comments_read_visible" on public.comments;
drop policy if exists "comments_admin_all"    on public.comments;
create policy "comments_read_visible" on public.comments for select
  using (hidden = false or public.is_admin());
create policy "comments_admin_all" on public.comments for all
  using (public.is_admin()) with check (public.is_admin());


