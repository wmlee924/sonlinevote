-- 6-1. artwork_stats : 작품별 하트 수 · (보이는) 댓글 수. 로그인 전에도 호출 가능
--   likes 표는 학생이 전체를 읽을 수 없으므로 개수는 이 함수로만 제공
create or replace function public.artwork_stats()
returns table (artwork_id uuid, like_count bigint, comment_count bigint)
language sql
stable
security definer
set search_path = public
as $$
  select a.id,
         (select count(*) from public.likes l where l.artwork_id = a.id),
         (select count(*) from public.comments c where c.artwork_id = a.id and c.hidden = false)
  from public.artworks a
  where a.hidden = false or public.is_admin();
$$;


