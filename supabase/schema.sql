-- =====================================================================
--  이 파일 전체를 Supabase 대시보드 → SQL Editor 에 붙여넣고 Run 하면
--  테이블 · RLS(행 단위 보안) 정책 · Storage 버킷 · 함수가 한 번에 만들어집니다.
--
--  ▶ 여러 번 실행해도 안전합니다. (create ... if not exists / create or replace /
--     drop policy if exists 패턴만 사용)  이미 저장된 데이터는 지워지지 않습니다.
--
--  ▶ 보안 설계 요약
--     - 학생은 Supabase "익명 로그인"으로 들어옵니다. (auth.uid() 는 있지만 이메일은 없음)
--     - 학생이 데이터를 "쓰는" 길은 아래 4개 함수뿐입니다.  (SECURITY DEFINER)
--         claim_student  : 학교·학번·이름으로 프로필 만들기/연결하기
--         toggle_like    : 하트 누르기 / 취소
--         add_comment    : 댓글 쓰기
--         delete_my_comment : 내 댓글 지우기
--       함수 안에서 투표 기간, 본인 여부, 글자 수를 다시 검사하므로
--       브라우저 코드를 고쳐도 규칙을 우회할 수 없습니다.
--     - 관리자(교사)는 이메일+비밀번호 계정이며 is_admin() 으로 판별합니다.
--     - 관리자 가입 코드는 secrets 표에만 있고, 브라우저에서는 읽을 수 없습니다.
-- =====================================================================


