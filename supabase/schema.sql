-- 2. 보조 함수 (순수 계산용)
-- ---------------------------------------------------------------------

-- 2-1. 학교 이름 정규화
--   "서울 고등학교" → "서울고",  "서울고등학교" → "서울고",  "서울고" → "서울고"
--   "한빛 초등학교" → "한빛초",  "한빛중학교" → "한빛중"
--   규칙: 모든 공백 제거 → 소문자 → 끝의 "등학교" 또는 "학교" 제거
create or replace function public.normalize_school(p_school text)
returns text
language sql
immutable
as $$
  select regexp_replace(
           lower(regexp_replace(coalesce(p_school, ''), '\s+', '', 'g')),
           '(등학교|학교)$', ''
         );
$$;


-- 2-2. 이름 마스킹
--   "강현욱" → "강*욱",  "김민" → "김*",  "남궁민수" → "남**수",  "A" → "*"
create or replace function public.mask_name(p_name text)
returns text
language sql
immutable
as $$
  select case
    when length(n) <= 1 then '*'
    when length(n) = 2  then left(n, 1) || '*'
    else left(n, 1) || repeat('*', length(n) - 2) || right(n, 1)
  end
  from (select trim(coalesce(p_name, '')) as n) s;
$$;


