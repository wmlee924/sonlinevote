-- 3. 권한 판별 함수
-- ---------------------------------------------------------------------

-- 3-1. is_admin() : 지금 요청한 사람이 관리자인가?
--   조건 ① 익명 계정이 아님  ② JWT 의 이메일이 admins 표에 있음
--   SECURITY DEFINER 라서 admins 표를 직접 읽을 권한이 없는 역할도 판별만은 가능
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(
    (
      auth.uid() is not null
      and coalesce((auth.jwt() ->> 'is_anonymous')::boolean, false) = false
      and exists (
        select 1 from public.admins a
        where lower(a.email) = lower(coalesce(auth.jwt() ->> 'email', ''))
      )
    ), false);
$$;


-- 3-2. my_student_id() : 지금 로그인한 익명 계정에 연결된 학생 프로필 id (없으면 null)
create or replace function public.my_student_id()
returns uuid
language sql
stable
security definer
set search_path = public
as $$
  select s.id from public.students s where s.auth_uid = auth.uid() limit 1;
$$;


