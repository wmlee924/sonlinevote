-- 1-1. settings : 사이트 전체 설정 (행이 딱 1개만 존재)
create table if not exists public.settings (
  id           integer primary key default 1 check (id = 1), -- 항상 1 (단일 행 보장)
  site_title   text not null default '캐릭터 공모전 투표',   -- 사이트 상단 제목
  notice       text not null default '마음에 드는 캐릭터에 하트를 눌러 주세요!', -- 안내문
  voting_open  boolean not null default false,              -- 투표 진행 중 여부 (스위치)
  updated_at   timestamptz not null default now()
);
-- 설정 행이 없으면 기본값으로 1개 만들어 둔다 (이미 있으면 건드리지 않음)
insert into public.settings (id) values (1) on conflict (id) do nothing;


-- 1-2. secrets : 서버 안에서만 쓰는 비밀 값 (관리자 가입 코드 등)
--      RLS 를 켜고 정책을 하나도 만들지 않으므로 브라우저(anon/authenticated)는 절대 읽을 수 없다.
create table if not exists public.secrets (
  key    text primary key,
  value  text not null
);
-- 관리자 가입 코드 기본값 'sonline'. 바꾸려면 SQL Editor 에서
--   update public.secrets set value = '새코드' where key = 'admin_signup_code';
insert into public.secrets (key, value) values ('admin_signup_code', 'sonline')
on conflict (key) do nothing;


-- 1-3. admins : 관리자(교사) 이메일 목록. 여기 있는 이메일로 로그인하면 관리자
create table if not exists public.admins (
  email       text primary key,
  created_at  timestamptz not null default now()
);


-- 1-4. students : 로그인한 학생 프로필
create table if not exists public.students (
  id             uuid primary key default gen_random_uuid(),
  school         text not null,          -- 학생이 입력한 학교 이름 (원문 그대로 보여주기용)
  school_key     text not null,          -- 띄어쓰기/"등학교·학교" 꼬리를 뺀 정규화 값 (중복 비교용)
  student_no     text not null,          -- 학번 (앞뒤 공백 제거)
  name           text not null,          -- 실제 이름 (관리자만 볼 수 있음)
  auth_uid       uuid unique,            -- 현재 연결된 익명 로그인 계정. 다른 기기에서 로그인하면 바뀜
  consent_at     timestamptz not null default now(), -- 개인정보 수집·이용 동의 시각
  created_at     timestamptz not null default now(),
  last_login_at  timestamptz not null default now()
);
-- 같은 (정규화한 학교, 학번) 은 프로필 1개만 허용 → 중복 투표 차단의 핵심
create unique index if not exists students_school_no_uniq
  on public.students (school_key, student_no);


-- 1-5. artworks : 출품작
create table if not exists public.artworks (
  id           uuid primary key default gen_random_uuid(),
  title        text not null,                      -- 작품 제목
  author       text not null default '',           -- 출품자
  description  text not null default '',           -- 작품 설명
  image_path   text not null,                      -- Storage 버킷 안의 파일 경로 (예: 2026/abc.png)
  hidden       boolean not null default false,     -- true 면 학생에게 보이지 않음
  sort_order   integer not null default 0,         -- 관리자 목록 정렬용
  created_at   timestamptz not null default now()
);


-- 1-6. likes : 하트 (작품당 학생 1명 1개)
create table if not exists public.likes (
  id          bigint generated by default as identity primary key,
  artwork_id  uuid not null references public.artworks (id) on delete cascade,
  student_id  uuid not null references public.students (id) on delete cascade,
  created_at  timestamptz not null default now(),
  unique (artwork_id, student_id)
);
create index if not exists likes_artwork_idx on public.likes (artwork_id);
create index if not exists likes_student_idx on public.likes (student_id);


-- 1-7. comments : 댓글
create table if not exists public.comments (
  id           bigint generated by default as identity primary key,
  artwork_id   uuid not null references public.artworks (id) on delete cascade,
  student_id   uuid not null references public.students (id) on delete cascade,
  body         text not null check (char_length(body) between 1 and 200), -- 200자 제한 (DB 에서도 검사)
  masked_name  text not null,                       -- 저장 시점에 마스킹한 이름 (예: 강*욱)
  hidden       boolean not null default false,      -- 관리자가 숨긴 댓글
  created_at   timestamptz not null default now()
);
create index if not exists comments_artwork_idx on public.comments (artwork_id);
create index if not exists comments_student_idx on public.comments (student_id);


