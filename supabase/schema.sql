-- 5. 학생용 쓰기 함수 (SECURITY DEFINER)
--    브라우저는 supabase.rpc('함수이름', {...}) 로만 호출합니다.
-- ---------------------------------------------------------------------

-- 5-1. claim_student : 학교·학번·이름으로 프로필을 만들거나 기존 프로필에 이 기기를 연결
--   - 미리 등록된 명단 없음 → 누구나 입력하면 참여
--   - 같은 (정규화 학교, 학번) 이 이미 있고 이름이 다르면 거부 (학번 도용 방지)
--   - 이미 있으면 auth_uid 를 지금 기기로 바꿈 → 이전 기기는 더 이상 투표 불가
--   - 반환: 프로필 요약 json
create or replace function public.claim_student(
  p_school     text,
  p_student_no text,
  p_name       text,
  p_consent    boolean
)
returns json
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid     uuid := auth.uid();
  v_school  text := trim(coalesce(p_school, ''));
  v_key     text;
  v_no      text := regexp_replace(trim(coalesce(p_student_no, '')), '\s+', '', 'g');
  v_name    text := regexp_replace(trim(coalesce(p_name, '')), '\s+', '', 'g');
  v_row     public.students%rowtype;
begin
  -- 로그인(익명 포함) 되어 있어야 함
  if v_uid is null then
    raise exception '로그인 정보가 없습니다. 페이지를 새로고침한 뒤 다시 시도해 주세요.';
  end if;
  -- 관리자 계정(이메일 계정)으로는 학생 프로필을 만들 수 없음
  if coalesce((auth.jwt() ->> 'is_anonymous')::boolean, false) = false then
    raise exception '학생 로그인은 익명 계정으로만 가능합니다.';
  end if;
  if not coalesce(p_consent, false) then
    raise exception '개인정보 수집·이용에 동의해야 참여할 수 있습니다.';
  end if;
  if v_school = '' or v_no = '' or v_name = '' then
    raise exception '학교, 학번, 이름을 모두 입력해 주세요.';
  end if;
  if char_length(v_school) > 40 or char_length(v_no) > 20 or char_length(v_name) > 20 then
    raise exception '입력값이 너무 깁니다.';
  end if;

  v_key := public.normalize_school(v_school);
  if v_key = '' then
    raise exception '학교 이름을 확인해 주세요.';
  end if;

  -- 같은 학교·학번 프로필이 이미 있는지 확인 (동시 요청 대비 행 잠금)
  select * into v_row
  from public.students
  where school_key = v_key and student_no = v_no
  for update;

  if found then
    -- 이름이 다르면 거부 (공백 제거 후 비교)
    if regexp_replace(v_row.name, '\s+', '', 'g') <> v_name then
      raise exception '이미 다른 이름으로 등록된 학번입니다. 학교·학번·이름을 다시 확인해 주세요.';
    end if;

    -- 이 기기(auth_uid)가 다른 학생 프로필에 연결돼 있었다면 그 연결은 끊음
    update public.students set auth_uid = null
    where auth_uid = v_uid and id <> v_row.id;

    -- 기존 프로필을 지금 기기로 연결 (이전 기기는 투표 불가가 됨)
    update public.students
    set auth_uid = v_uid, last_login_at = now(), school = v_school
    where id = v_row.id
    returning * into v_row;
  else
    -- 이 기기가 다른 프로필에 연결돼 있었다면 끊음 (auth_uid unique 때문에 필요)
    update public.students set auth_uid = null where auth_uid = v_uid;

    insert into public.students (school, school_key, student_no, name, auth_uid)
    values (v_school, v_key, v_no, v_name, v_uid)
    returning * into v_row;
  end if;

  return json_build_object(
    'id',          v_row.id,
    'school',      v_row.school,
    'student_no',  v_row.student_no,
    'name',        v_row.name,
    'masked_name', public.mask_name(v_row.name)
  );
end;
$$;


-- 5-2. toggle_like : 하트 누르기/취소. 반환 { liked: true/false, like_count: n }
create or replace function public.toggle_like(p_artwork_id uuid)
returns json
language plpgsql
security definer
set search_path = public
as $$
declare
  v_student uuid;
  v_open    boolean;
  v_liked   boolean;
  v_count   integer;
begin
  select voting_open into v_open from public.settings where id = 1;
  if not coalesce(v_open, false) then
    raise exception '지금은 투표 기간이 아닙니다.';
  end if;

  v_student := public.my_student_id();
  if v_student is null then
    raise exception '로그인이 필요합니다. (다른 기기에서 로그인했다면 이 기기는 연결이 해제되었습니다)';
  end if;

  if not exists (select 1 from public.artworks where id = p_artwork_id and hidden = false) then
    raise exception '존재하지 않거나 숨겨진 작품입니다.';
  end if;

  -- 이미 눌렀으면 취소, 아니면 추가
  delete from public.likes where artwork_id = p_artwork_id and student_id = v_student;
  if found then
    v_liked := false;
  else
    insert into public.likes (artwork_id, student_id) values (p_artwork_id, v_student);
    v_liked := true;
  end if;

  select count(*) into v_count from public.likes where artwork_id = p_artwork_id;
  return json_build_object('liked', v_liked, 'like_count', v_count);
end;
$$;


-- 5-3. add_comment : 댓글 작성 (200자 제한, 작성자명은 저장 시점에 마스킹)
--   반환: 방금 저장한 댓글 1건 (학생 화면에 바로 붙이기 위함)
create or replace function public.add_comment(p_artwork_id uuid, p_body text)
returns json
language plpgsql
security definer
set search_path = public
as $$
declare
  v_student public.students%rowtype;
  v_open    boolean;
  v_body    text := trim(coalesce(p_body, ''));
  v_row     public.comments%rowtype;
begin
  select voting_open into v_open from public.settings where id = 1;
  if not coalesce(v_open, false) then
    raise exception '지금은 투표 기간이 아닙니다.';
  end if;

  select * into v_student from public.students where auth_uid = auth.uid();
  if not found then
    raise exception '로그인이 필요합니다. (다른 기기에서 로그인했다면 이 기기는 연결이 해제되었습니다)';
  end if;

  if char_length(v_body) = 0 then
    raise exception '댓글 내용을 입력해 주세요.';
  end if;
  if char_length(v_body) > 200 then
    raise exception '댓글은 200자까지만 쓸 수 있습니다.';
  end if;

  if not exists (select 1 from public.artworks where id = p_artwork_id and hidden = false) then
    raise exception '존재하지 않거나 숨겨진 작품입니다.';
  end if;

  insert into public.comments (artwork_id, student_id, body, masked_name)
  values (p_artwork_id, v_student.id, v_body, public.mask_name(v_student.name))
  returning * into v_row;

  return json_build_object(
    'id',          v_row.id,
    'artwork_id',  v_row.artwork_id,
    'student_id',  v_row.student_id,
    'body',        v_row.body,
    'masked_name', v_row.masked_name,
    'created_at',  v_row.created_at
  );
end;
$$;


-- 5-4. delete_my_comment : 내 댓글만 삭제. 반환: 삭제됐으면 true
create or replace function public.delete_my_comment(p_comment_id bigint)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_student uuid := public.my_student_id();
begin
  if v_student is null then
    raise exception '로그인이 필요합니다.';
